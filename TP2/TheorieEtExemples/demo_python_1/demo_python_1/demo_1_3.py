# Calculer la valeur de l’hypoténuse d’un triangle rectangle dont les
# côtés de l’angle droit mesurent 3 et 4 unités, respectivement.

# Déclarer les variables
cote_a = 3
cote_b = 4

# Calculer l'hypoténuse
hypotenuse = (cote_a**2 + cote_b**2)**(1/2)

# Afficher les résultats
print(hypotenuse)
