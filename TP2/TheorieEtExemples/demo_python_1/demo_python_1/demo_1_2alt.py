# Calculer la circonférence d’un cercle dont le rayon est de 4 cm.

# Importer les modules supplémentaires
import math

# Déclarer les constantes et variables
PI = math.pi
rayon = 4

# Calculer la circonférence
circonference = 2 * PI * rayon

# Afficher les résultats
print(circonference)
